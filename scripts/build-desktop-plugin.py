#!/usr/bin/env python3
"""Build the single-file Desktop plugin artifact (desktop/plugin.js).

The Hermes Desktop runtime blob loader evaluates `desktop/plugin.js` from a
Blob URL: relative imports cannot resolve there, and only the public SDK
specifiers (`@hermes/plugin-sdk`, `react`, `react/jsx-runtime`,
`react/jsx-dev-runtime`) are allowed. This script therefore INLINES the owned
modular sources (`desktop/pane.mjs`, `desktop/logic.mjs`) between the BEGIN/END
markers, strips their `import`/`export` statements (the artifact declares the
React + SDK imports once at the top), and verifies the result imports only
allowlisted specifiers.

Usage:
    python3 scripts/build-desktop-plugin.py           # regenerate
    python3 scripts/build-desktop-plugin.py --check   # verify, write nothing

Exit status is 0 on success (and, for --check, byte identity), 1 on a stale or
invalid artifact. Idempotent: the artifact is a pure function of the two
sources and this script.
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ENTRY = REPO / "desktop" / "plugin.js"
SOURCES = [REPO / "desktop" / "logic.mjs", REPO / "desktop" / "pane.mjs"]

ALLOWED_SPECIFIERS = {
    "@hermes/plugin-sdk",
    "react",
    "react/jsx-runtime",
    "react/jsx-dev-runtime",
}

IMPORT_RE = re.compile(r"^import[\s\S]*?from\s+'([^']+)'", re.M)
BARE_IMPORT_RE = re.compile(r"^import\s+'([^']+)'", re.M)
EXPORT_DEFAULT_RE = re.compile(r"^export default ", re.M)
EXPORT_NAMED_RE = re.compile(r"^export (const|function|class|let|var) ", re.M)
BEGIN = "/* ===== BEGIN inlined: {name} ({note}) ===== */\n"
END = "/* ===== END inlined: {name} ===== */\n"


def strip_module_syntax(source: str) -> str:
    """Remove import statements and rewrite export statements for inlining."""
    out = IMPORT_RE.sub("", source)
    out = BARE_IMPORT_RE.sub("", out)
    out = EXPORT_DEFAULT_RE.sub("const __pane_default = ", out)
    out = EXPORT_NAMED_RE.sub(r"\1 ", out)
    # Named re-exports (`export { A, B } from …`) must not survive either.
    out = re.sub(r"^export \{[^}]*\}[^\n]*\n", "", out, flags=re.M)
    return out.strip("\n")


def build_artifact() -> str:
    """Return the artifact text; pure function of the owned sources."""
    preamble = f"""/**\n * Hermes Advisor — Desktop plugin loader entry (SINGLE self-contained file).\n *\n * The runtime blob pipeline imports this file from a Blob URL: relative\n * imports cannot resolve there, and only the public SDK specifiers are\n * allowed. This file is GENERATED by `scripts/build-desktop-plugin.py` from\n * the owned modular sources (`desktop/pane.mjs`, `desktop/logic.mjs`) — edit\n * those and rebuild, never hand-edit the inlined sections.\n *\n * Supported public specifiers (the loader's runtime allowlist):\n * `@hermes/plugin-sdk`, `react`, `react/jsx-runtime`, `react/jsx-dev-runtime`.\n * Anything else is refused up-front.\n *\n * Exports: default HermesPlugin registration object.\n */\n\nimport {{ host, useValue, Button, Checkbox, EmptyState, ErrorState, GlyphSpinner, Input, Textarea }} from '@hermes/plugin-sdk'\nimport React from 'react'\n"""

    sections = []
    for src in SOURCES:
        name = src.name
        text = strip_module_syntax(src.read_text(encoding="utf-8"))
        if re.search(r"^export\s", text, flags=re.M):
            raise ValueError(f"{name} still contains an export statement after inlining")
        note = "canonical source of truth"
        sections.append(BEGIN.format(name=name, note=note) + text + "\n" + END.format(name=name))

    body = "\n\n".join(sections)
    tail = "\n\nexport default __pane_default\n"
    artifact = preamble + "\n" + body + tail

    # Verify: every import specifier in the artifact is allowlisted, and no
    # relative or absolute path import survived the rewrite.
    specs = set(IMPORT_RE.findall(artifact)) | set(BARE_IMPORT_RE.findall(artifact))
    bad = specs - ALLOWED_SPECIFIERS
    if bad:
        raise ValueError(f"artifact imports non-allowlisted specifiers: {sorted(bad)}")
    relative = [spec for spec in specs if spec.startswith((".", "/"))]
    if relative:
        raise ValueError(f"artifact contains path imports: {sorted(relative)}")
    return artifact


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify desktop/plugin.js is byte-identical to a fresh build; do not write",
    )
    args = parser.parse_args(argv)

    try:
        artifact = build_artifact()
    except (OSError, ValueError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    digest = hashlib.sha256(artifact.encode("utf-8")).hexdigest()
    size = len(artifact.encode("utf-8"))

    if args.check:
        if not ENTRY.exists():
            print(f"ERROR: {ENTRY} is missing; run scripts/build-desktop-plugin.py", file=sys.stderr)
            return 1
        current = ENTRY.read_text(encoding="utf-8")
        if current != artifact:
            print(
                f"ERROR: {ENTRY} is stale; run scripts/build-desktop-plugin.py "
                f"(expected sha256={digest}, found sha256={hashlib.sha256(current.encode('utf-8')).hexdigest()})",
                file=sys.stderr,
            )
            return 1
        print(f"artifact up to date: {ENTRY} ({size} bytes, sha256={digest})")
        return 0

    ENTRY.write_text(artifact, encoding="utf-8", newline="\n")
    print(f"wrote {ENTRY} ({size} bytes, sha256={digest}, imports: {sorted(set(IMPORT_RE.findall(artifact)) | set(BARE_IMPORT_RE.findall(artifact)))})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
